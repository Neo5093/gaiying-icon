/* SVG 矢量导出（文字 / 内置图标 / 在线图标 / SVG 粘贴时为精确矢量，其余为嵌入位图） */
async function buildSvg(size = 512) {
  const st = state;
  const defs = [], body = [];
  // 背景
  if (st.layers.bg && st.bg.type !== "none") {
    if (st.bg.type === "solid") body.push(`<rect width="${size}" height="${size}" fill="${st.bg.c1}"/>`);
    else {
      const a = ((st.bg.angle - 90) * Math.PI) / 180;
      const x2 = 50 + Math.cos(a) * 50, y2 = 50 + Math.sin(a) * 50;
      if (st.bg.type === "radial")
        defs.push(`<radialGradient id="bgg"><stop offset="0" stop-color="${st.bg.c1}"/><stop offset="1" stop-color="${st.bg.c2}"/></radialGradient>`);
      else
        defs.push(`<linearGradient id="bgg" x1="${100 - x2}%" y1="${100 - y2}%" x2="${x2}%" y2="${y2}%"><stop offset="0" stop-color="${st.bg.c1}"/><stop offset="1" stop-color="${st.bg.c2}"/></linearGradient>`);
      body.push(`<rect width="${size}" height="${size}" fill="url(#bgg)"/>`);
    }
  }
  // 前景
  const box = size * st.fg.scale;
  const tx = size / 2 + (st.fg.dx / 100) * size, ty = size / 2 + (st.fg.dy / 100) * size;
  const tf = `translate(${tx} ${ty}) rotate(${st.fg.rot})${st.fg.flip ? " scale(-1 1)" : ""}`;
  const fillRef = st.tint.mode === "gradient" ? "url(#fgg)" : st.tint.c1;
  if (st.tint.mode === "gradient")
    defs.push(`<linearGradient id="fgg" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="${st.tint.c1}"/><stop offset="1" stop-color="${st.tint.c2}"/></linearGradient>`);

  if ((st.source === "clipart" || st.source === "brand") && !st.clipart.svg) {
    const icon = BUILTIN_ICONS.find(i => i.n === st.clipart.id) || BUILTIN_ICONS[0];
    body.push(`<g transform="${tf}"><path transform="translate(${-box / 2} ${-box / 2}) scale(${box / 24})" d="${icon.d}" fill="${fillRef}"${icon.fr ? ` fill-rule="${icon.fr}"` : ""}/></g>`);
  } else if ((st.source === "clipart" || st.source === "brand") && st.clipart.svg) {
    const vb = st.clipart.vb || "0 0 24 24";
    const [, , vw] = vb.split(/\s+/).map(Number);
    const inner = st.tint.mode === "original" ? st.clipart.svg : st.clipart.svg.replace(/currentColor/g, fillRef);
    body.push(`<g transform="${tf}"><g transform="translate(${-box / 2} ${-box / 2}) scale(${box / (vw || 24)})">${inner}</g></g>`);
  } else if (st.source === "text") {
    const lines = (st.text.value || "A").split("\n");
    const fs = box * 0.7 / Math.max(1, lines.length * 0.9);
    body.push(`<g transform="${tf}">` + lines.map((l, i) =>
      `<text x="0" y="${(i - (lines.length - 1) / 2) * fs * st.text.lh}" font-family="${st.text.font}" font-weight="${st.text.weight}" font-size="${fs}" fill="${fillRef}" text-anchor="middle" dominant-baseline="central">${l.replace(/&/g, "&amp;").replace(/</g, "&lt;")}</text>`).join("") + "</g>");
  } else {
    // 位图内容：嵌入渲染结果（含图像调整）
    const cv = makeCanvas(Math.round(box) || 2);
    const content = await drawContent(st, cv.width);
    applyAdjustments(content, st.adjust);
    body.push(`<g transform="${tf}"><image href="${content.toDataURL()}" x="${-box / 2}" y="${-box / 2}" width="${box}" height="${box}"/></g>`);
  }
  // 徽章（圆点样式带内容，与画布渲染对齐）
  if (st.layers.badge && st.badge.on) {
    const b = st.badge;
    const esc = s => s.replace(/&/g, "&amp;").replace(/</g, "&lt;");
    const fsz = size * 0.1 * (b.size / 0.3);
    if (b.style === "bar") {
      const h = size * 0.2 * (b.size / 0.3);
      body.push(`<rect y="${size - h}" width="${size}" height="${h}" fill="${b.bg}"/>`);
      body.push(`<text x="${size / 2}" y="${size - h / 2 + fsz * 0.05}" font-family="Inter,'Noto Sans SC',sans-serif" font-weight="800" font-size="${fsz}" fill="${b.fg}" text-anchor="middle" dominant-baseline="central">${esc(b.text)}</text>`);
    } else if (b.style === "dot") {
      const r = size * 0.12 * (b.size / 0.3);
      const [bx, by] = { tl: [r * 1.2, r * 1.2], tr: [size - r * 1.2, r * 1.2], bl: [r * 1.2, size - r * 1.2], br: [size - r * 1.2, size - r * 1.2] }[b.pos];
      const cx = bx + (b.dx || 0) / 100 * size, cy = by + (b.dy || 0) / 100 * size;
      body.push(`<circle cx="${cx}" cy="${cy}" r="${r}" fill="${b.bg}"/>`);
      const dt = b.dotType || "none";
      if (dt === "icon") {
        const isz = r * 2 * 0.62;
        if (b.dotIconSvg) { // 在线 Iconify
          const vb = (b.dotIconVb || "0 0 24 24").split(/\s+/).map(Number);
          const ar = (vb[2] || 24) / (vb[3] || 24);
          const dw = ar >= 1 ? isz : isz * ar, dh = ar >= 1 ? isz / ar : isz;
          const inner = b.dotIconSvg.replace(/currentColor/g, b.fg);
          body.push(`<g transform="translate(${cx - dw / 2} ${cy - dh / 2}) scale(${dw / (vb[2] || 24)} ${dh / (vb[3] || 24)}) translate(${-(vb[0] || 0)} ${-(vb[1] || 0)})">${inner}</g>`);
        } else {
          const icon = BUILTIN_ICONS.find(i => i.n === b.dotIcon);
          if (icon) body.push(`<path transform="translate(${cx - isz / 2} ${cy - isz / 2}) scale(${isz / 24})" d="${icon.d}" fill="${b.fg}"${icon.fr ? ` fill-rule="${icon.fr}"` : ""}/>`);
        }
      } else if (dt === "emoji" && b.dotEmoji) {
        body.push(`<text x="${cx}" y="${cy + r * 0.06}" font-size="${r * 2 * 0.6}" text-anchor="middle" dominant-baseline="central">${esc(b.dotEmoji)}</text>`);
      } else if (dt === "image" && b.dotImage) {
        defs.push(`<clipPath id="dotclip"><circle cx="${cx}" cy="${cy}" r="${r * 0.92}"/></clipPath>`);
        body.push(`<image href="${b.dotImage}" x="${cx - r}" y="${cy - r}" width="${r * 2}" height="${r * 2}" preserveAspectRatio="xMidYMid slice" clip-path="url(#dotclip)"/>`);
      }
    } else { // ribbon
      const w = size * Math.SQRT2 * 0.42 * (b.size / 0.3);
      const fx = b.pos === "tl" || b.pos === "bl" ? -1 : 1;
      const fy = b.pos === "bl" || b.pos === "br" ? -1 : 1;
      const bh = fsz * 1.5;
      body.push(`<g transform="translate(${fx === 1 ? size : 0} ${fy === 1 ? 0 : size}) scale(${fx} ${fy}) rotate(45)"><rect x="${-w / 2}" y="${w * 0.28 - bh / 2}" width="${w}" height="${bh}" fill="${b.bg}"/><text x="0" y="${w * 0.28 + fsz * 0.04}" font-family="Inter,'Noto Sans SC',sans-serif" font-weight="800" font-size="${fsz}" fill="${b.fg}" text-anchor="middle" dominant-baseline="central">${esc(b.text)}</text></g>`);
    }
  }
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}">${defs.length ? `<defs>${defs.join("")}</defs>` : ""}${body.join("")}</svg>`;
}

/* ── 导出文件清单（用于预览 + 实际生成）── */
function exportPlan() {
  const P = EXPORT_OPTS;
  const files = [];
  const add = (path, gen) => files.push({ path, gen });

  if (P.platforms.has("android")) {
    for (const [d, sz] of ANDROID_DENSITIES) {
      add(`android/mipmap-${d}/ic_launcher.png`, () => renderPng(sz, { shape: "rounded", radius: 18 }));
      add(`android/mipmap-${d}/ic_launcher_round.png`, () => renderPng(sz, { shape: "circle" }));
    }
    for (const [d, sz] of ANDROID_FG) {
      add(`android/mipmap-${d}/ic_launcher_foreground.png`, () => renderPng(sz, { bgOn: false, badgeOn: false, fgFactor: 2 / 3 }));
      add(`android/mipmap-${d}/ic_launcher_background.png`, () => renderPng(sz, { fgOn: false, badgeOn: false }));
      add(`android/mipmap-${d}/ic_launcher_monochrome.png`, () => renderPng(sz, { mono: "#ffffff", fgFactor: 2 / 3 }));
    }
    add("android/mipmap-anydpi-v26/ic_launcher.xml", () => adaptiveXml(true));
    add("android/mipmap-anydpi-v26/ic_launcher_round.xml", () => adaptiveXml(true));
    add("android/playstore-icon-512.png", () => renderPng(512, { shape: "square" }));
  }
  if (P.platforms.has("ios")) {
    for (const [fn, sz] of IOS_ICONS)
      add(`ios/AppIcon.appiconset/${fn}`, () => renderPng(sz, { shape: "square" }));
    add("ios/AppIcon.appiconset/Contents.json", () => iosContentsJson());
  }
  if (P.platforms.has("web")) {
    add("web/favicon.ico", async () => {
      const list = [];
      for (const sz of [16, 32, 48]) list.push({ size: sz, data: await renderPng(sz, webShape()) });
      return buildIco(list);
    });
    for (const sz of [16, 32, 96]) add(`web/favicon-${sz}x${sz}.png`, () => renderPng(sz, webShape()));
    add("web/apple-touch-icon.png", () => renderPng(180, { shape: "square" }));
    for (const sz of [192, 512]) add(`web/icon-${sz}x${sz}.png`, () => renderPng(sz, webShape()));
    add("web/icon-maskable-512x512.png", () => renderPng(512, { shape: "square" }));
    add("web/og-image.png", async () => {
      const cv = makeCanvas(1200, 630);
      await renderOg(cv.getContext("2d"), 1200, 630);
      return canvasToBytes(cv);
    });
    add("web/manifest.json", () => webManifest());
    add("web/snippet.html", () => webSnippet());
  }
  if (P.platforms.has("macos")) {
    add("macos/AppIcon.icns", async () => {
      const list = [];
      for (const sz of [16, 32, 64, 128, 256, 512, 1024])
        list.push({ size: sz, data: await renderPng(sz, { shape: "squircle", pad: 0.075 }) });
      return buildIcns(list);
    });
    for (const sz of [512, 1024])
      add(`macos/icon_${sz}x${sz}.png`, () => renderPng(sz, { shape: "squircle", pad: 0.075 }));
  }
  if (P.platforms.has("windows")) {
    add("windows/app.ico", async () => {
      const list = [];
      for (const sz of [16, 24, 32, 48, 64, 256]) list.push({ size: sz, data: await renderPng(sz, webShape()) });
      return buildIco(list);
    });
    for (const sz of [44, 71, 150, 310]) add(`windows/Square${sz}x${sz}Logo.png`, () => renderPng(sz, { shape: "square" }));
  }
  for (const sz of P.customSizes)
    add(`custom/icon-${sz}x${sz}.png`, () => renderPng(sz, webShape()));

  if (P.formats.has("webp"))
    for (const sz of [192, 512]) add(`extra/icon-${sz}.webp`, () => renderPng(sz, webShape(), "image/webp", 0.95));
  if (P.formats.has("svg"))
    add("extra/icon.svg", () => buildSvg(512));

  add("qm-icon-config.json", () => JSON.stringify(state, null, 2));
  add("README.md", () => readmeText());
  return files;
}

