/* 文件树文本 */
function fileTreeText(files) {
  return files.map(f => f.path).join("\n");
}

/* 执行导出 */
async function runExport(onProgress) {
  const files = exportPlan();
  const zip = new ZipBuilder();
  for (let i = 0; i < files.length; i++) {
    const f = files[i];
    let data = await f.gen();
    zip.add(f.path, data);
    onProgress && onProgress((i + 1) / files.length, f.path);
  }
  const blob = zip.build();
  const a = document.createElement("a");
  a.href = URL.createObjectURL(blob);
  a.download = `${(state.name || "icon").replace(/[^\w一-龥-]+/g, "-")}-icons.zip`;
  a.click();
  setTimeout(() => URL.revokeObjectURL(a.href), 5000);
  return files.length;
}
