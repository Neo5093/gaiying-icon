const EXPORT_OPTS = { platforms: new Set(["android", "ios", "web", "macos", "windows"]), formats: new Set(["png"]), customSizes: [] };

async function canvasToBytes(canvas, type = "image/png", quality) {
  const blob = await new Promise(r => canvas.toBlob(r, type, quality));
  return new Uint8Array(await blob.arrayBuffer());
}

/* 渲染指定配置到 PNG 字节 */
async function renderPng(size, opts, type = "image/png", quality) {
  const cv = makeCanvas(size);
  await renderIcon(cv.getContext("2d"), size, opts);
  return canvasToBytes(cv, type, quality);
}

